import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { supabase, isMockMode } from "@/lib/supabase";
import { useAuth } from "./useAuth";
import type { Order, OrderItem } from "@/lib/database.types";

export interface OrderWithItems extends Order {
  order_items: (OrderItem & { listing_snapshot: { title: string; slug: string; resale_price: number } })[];
}

// ─── Buyer: my orders ─────────────────────────────────────────
export function useOrders() {
  const { user } = useAuth();
  return useQuery({
    queryKey: ["orders", user?.id],
    queryFn: async (): Promise<OrderWithItems[]> => {
      if (isMockMode || !user) return mockOrders as OrderWithItems[];

      const { data, error } = await supabase
        .from("orders")
        .select("*, order_items(*)")
        .eq("buyer_id", user.id)
        .order("created_at", { ascending: false });

      if (error) throw error;
      return (data ?? []) as OrderWithItems[];
    },
    enabled: !!user || isMockMode,
  });
}

// ─── Admin: all orders ────────────────────────────────────────
export function useAdminOrders(status?: string) {
  return useQuery({
    queryKey: ["admin-orders", status],
    queryFn: async (): Promise<OrderWithItems[]> => {
      if (isMockMode) {
        let list = mockOrders as OrderWithItems[];
        if (status) list = list.filter((o) => o.status === status);
        return list;
      }

      let query = supabase
        .from("orders")
        .select("*, order_items(*)")
        .order("created_at", { ascending: false });
      if (status) query = query.eq("status", status);
      const { data, error } = await query;
      if (error) throw error;
      return (data ?? []) as OrderWithItems[];
    },
    enabled: true,
  });
}

// ─── Admin: update order status ───────────────────────────────
export function useUpdateOrderStatus() {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: async ({ orderId, status }: { orderId: string; status: Order["status"] }) => {
      const { error } = await supabase
        .from("orders")
        .update({ status })
        .eq("id", orderId);
      if (error) throw error;

      // If marking fulfilled, trigger WhatsApp/email notification via Edge Function
      if (status === "fulfilled") {
        await supabase.functions.invoke("send-order-confirmation", {
          body: { orderId, event: "fulfilled" },
        });
      }
    },
    onSuccess: () => queryClient.invalidateQueries({ queryKey: ["admin-orders"] }),
  });
}

// ─── Create Stripe checkout session ──────────────────────────
// Called when buyer clicks "Place order" on checkout page.
// Returns Stripe hosted checkout URL generated by Supabase Edge Function.
export async function createCheckoutSession(
  listingIds: string[],
  shippingAddress: {
    name: string; phone: string; email: string;
    address: string; city: string; postal?: string;
  }
): Promise<{ url: string } | { error: string }> {
  if (isMockMode) {
    return { url: "/checkout/success?session_id=mock_session_demo" };
  }

  const response = await supabase.functions.invoke("create-checkout-session", {
    body: { listingIds, shippingAddress },
  });

  if (response.error) {
    // Check if the response contains custom JSON error message
    try {
      const errContext = await response.error.context.json();
      if (errContext?.error) return { error: errContext.error };
    } catch {
      // ignore
    }
    return { error: response.error.message || "Failed to create Stripe payment session." };
  }

  if (response.data?.error) {
    return { error: response.data.error };
  }

  return response.data as { url: string };
}

